# Actuator through the frontend origin: health must come from Spring Boot (JSON + X-Request-Id);
# every other actuator path must be a 404 from nginx itself, neither proxied nor the SPA's index.html.
function Probe([string]$url) {
    $bodyFile = Join-Path $Tmp "probe.txt"
    $headers = (& curl.exe -s -D - -o $bodyFile $url) -join "`n"
    $status = if ($headers -match 'HTTP/[\d.]+ (\d{3})') { $Matches[1] } else { "000" }
    $type = if ($headers -match '(?im)^Content-Type:\s*([^\r\n;]+)') { $Matches[1].Trim() } else { "" }
    $proxied = $headers -match '(?im)^X-Request-Id:'
    $body = if (Test-Path $bodyFile) { [IO.File]::ReadAllText($bodyFile) } else { "" }
    return [pscustomobject]@{ Status = $status; Type = $type; Proxied = $proxied; Html = $body.Contains('<div id="root">'); Body = $body }
}
