<#
Starts the complete stack (PostgreSQL + analyzer + Spring Boot + React frontend) with Docker Compose,
waits for health checks, then exercises the API end to end against the running stack.

Run:   powershell -ExecutionPolicy Bypass -File "$env:USERPROFILE\Documents\API-Sentinel\scripts\demo-backend.ps1"
Stop:  docker compose -f infrastructure\docker-compose.yml --env-file .env down      (keeps data)
Wipe:  docker compose -f infrastructure\docker-compose.yml --env-file .env down -v   (deletes the database volume)

Output: logs\demo-backend.txt (summary) and logs\demo\ (raw responses, report, contract-test zip).
Secrets are generated into .env (git-ignored) on first run and are never printed.
#>
param([switch]$NoBuild)
$ErrorActionPreference = "Continue"
$Root = Split-Path -Parent $PSScriptRoot
$Log = Join-Path $Root "logs\demo-backend.txt"
$Out = Join-Path $Root "logs\demo"
New-Item -ItemType Directory -Force -Path $Out | Out-Null
Set-Content -Path $Log -Value "API Sentinel backend demo $(Get-Date -Format o)" -Encoding utf8

$env:Path = [Environment]::GetEnvironmentVariable("Path", "Machine") + ";" + [Environment]::GetEnvironmentVariable("Path", "User")
$dockerBin = Join-Path $env:ProgramFiles "Docker\Docker\resources\bin"
if (-not (Get-Command docker -ErrorAction SilentlyContinue) -and (Test-Path $dockerBin)) { $env:Path = "$dockerBin;$env:Path" }
if (-not (& docker version --format "{{.Server.Version}}" 2>$null)) { Write-Host "Docker engine is not running." -ForegroundColor Red; exit 2 }

function Say([string]$text) { Write-Host $text; Add-Content -Path $Log -Value $text -Encoding utf8 }
$script:failures = 0
function Check([string]$name, [bool]$ok, [string]$detail = "") {
    $tag = if ($ok) { "PASS" } else { "FAIL"; $script:failures++ }
    Say ("[{0}] {1}{2}" -f $tag, $name, $(if ($detail) { " - $detail" } else { "" }))
}

# ------------------------------------------------------------------ secrets (.env)
function New-Secret([int]$bytes) {
    $b = New-Object byte[] $bytes
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b)
    return $b
}
$EnvFile = Join-Path $Root ".env"
$existing = @{}
if (Test-Path $EnvFile) {
    Get-Content $EnvFile | Where-Object { $_ -match '^\s*([A-Z0-9_]+)=(.*)$' } | ForEach-Object { $existing[$Matches[1]] = $Matches[2] }
}
$generated = [ordered]@{
    POSTGRES_DB                = "apisentinel"
    POSTGRES_USER              = "apisentinel"
    POSTGRES_PASSWORD          = ([BitConverter]::ToString((New-Secret 24)) -replace "-", "").ToLower()
    APISENTINEL_JWT_SECRET     = [Convert]::ToBase64String((New-Secret 48))
    APISENTINEL_INTERNAL_TOKEN = ([Convert]::ToBase64String((New-Secret 32)) -replace '\+', '-' -replace '/', '_').TrimEnd('=')
    APISENTINEL_BACKEND_PORT   = "8080"
}
$added = @()
foreach ($key in $generated.Keys) {
    if (-not $existing.ContainsKey($key) -or -not $existing[$key] -or $existing[$key] -like "replace-with*") {
        $existing[$key] = $generated[$key]; $added += $key
    }
}
if ($added.Count -gt 0) {
    # Rewrite only when something was missing; existing values are kept as they were.
    $lines = @("# Generated by scripts/demo-backend.ps1. Local secrets: never commit this file.")
    foreach ($k in $existing.Keys | Sort-Object) { $lines += "$k=$($existing[$k])" }
    [IO.File]::WriteAllLines($EnvFile, $lines)
    Say "Secrets: generated $($added -join ', ') into .env (values not shown)."
} else { Say "Secrets: using existing .env (values not shown)." }
$Port = $existing["APISENTINEL_BACKEND_PORT"]
$Base = "http://127.0.0.1:$Port"
$Compose = @("compose", "-f", (Join-Path $Root "infrastructure\docker-compose.yml"), "--env-file", $EnvFile)

# ------------------------------------------------------------------ build & start
Say "`n== docker compose build + up (waits for health checks)"
if (-not $NoBuild) {
    & docker @Compose build 2>&1 | Select-Object -Last 5 | ForEach-Object { Say "  $_" }
    if ($LASTEXITCODE -ne 0) { Say "Build failed."; exit 1 }
}
& docker @Compose up -d --wait --wait-timeout 180 2>&1 | ForEach-Object { Say "  $_" }
$up = $LASTEXITCODE
& docker @Compose ps --format "table {{.Service}}\t{{.State}}\t{{.Health}}\t{{.Ports}}" 2>&1 | ForEach-Object { Say "  $_" }
Check "compose up --wait (all services healthy)" ($up -eq 0)
if ($up -ne 0) { & docker @Compose logs --tail 60 backend 2>&1 | ForEach-Object { Say "  $_" }; exit 1 }

# ------------------------------------------------------------------ HTTP helper (curl.exe; bodies via files)
$Tmp = Join-Path $env:TEMP "apisentinel-demo"; New-Item -ItemType Directory -Force -Path $Tmp | Out-Null
function Api([string]$method, [string]$path, $body = $null, [string]$token = $null, [string]$save = $null, [string[]]$form = $null) {
    $outFile = if ($save) { Join-Path $Out $save } else { Join-Path $Tmp "resp.bin" }
    $curlArgs = @("-s", "-o", $outFile, "-w", "%{http_code}", "-X", $method, "$Base$path")
    if ($token) { $curlArgs += @("-H", "Authorization: Bearer $token") }
    if ($null -ne $body) {
        $bodyFile = Join-Path $Tmp "body.json"
        [IO.File]::WriteAllText($bodyFile, ($body | ConvertTo-Json -Depth 10 -Compress))
        $curlArgs += @("-H", "Content-Type: application/json", "--data-binary", "@$bodyFile")
    }
    if ($form) { foreach ($f in $form) { $curlArgs += @("-F", $f) } }
    $status = [int](& curl.exe @curlArgs)
    $text = if (Test-Path $outFile) { [IO.File]::ReadAllText($outFile) } else { "" }
    $json = $null; try { $json = $text | ConvertFrom-Json } catch { }
    return [pscustomobject]@{ Status = $status; Json = $json; Text = $text; File = $outFile }
}

